 ADD COLUMN tasa_iva DECIMAL(5,4) NOT NULL DEFAULT 0,
 ADD CONSTRAINT chk_concepto_monto CHECK (monto_base >= 0),
 ADD CONSTRAINT chk_tasa_iva CHECK (tasa_iva BETWEEN 0 AND 1);
CREATE TABLE horarios (
 id_horario INT AUTO_INCREMENT PRIMARY KEY,
 id_asignacion INT NOT NULL,
 dia_semana TINYINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
 hora_inicio TIME NOT NULL,
 hora_fin TIME NOT NULL,
 FOREIGN KEY (id_asignacion) REFERENCES asignaciones_profesor(id_asignacion),
 CHECK (hora_inicio < hora_fin),
 UNIQUE KEY horario_unico (id_asignacion,dia_semana,hora_inicio)
) ENGINE=InnoDB COMMENT='Franjas de clase por asignación';
CREATE TABLE tarifas_estudiante (
 id_tarifa INT AUTO_INCREMENT PRIMARY KEY,
 id_estudiante INT NOT NULL,
